/// Which rendering an eligibility failure came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Rendering {
    /// The pristine function.
    Original,
    /// The function after the candidate edit.
    Mutant,
}

/// A function-shape feature outside the verified fragment.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum FunctionFeature {
    /// Type or lifetime parameters, or a where clause.
    Generic,
    /// A const function.
    Const,
    /// An async function.
    Async,
    /// An unsafe function.
    Unsafe,
    /// An explicitly `safe fn`; the fragment fixes one spelling of safety.
    ExplicitSafe,
    /// A non-Rust ABI.
    Extern,
    /// A variadic signature.
    Variadic,
    /// A receiver rather than a free-function argument.
    Receiver,
}

/// A type feature outside the closed symbolic domain.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum TypeFeature {
    /// A reference could observe aliasing or external state.
    Reference,
    /// A raw pointer has provenance and memory effects outside this model.
    RawPointer,
    /// A slice is unsized and is not minted by value.
    Slice,
    /// A function pointer may call code outside the fragment.
    FunctionPointer,
    /// A trait object has an open implementation set.
    TraitObject,
    /// An `impl Trait` has an intentionally hidden concrete type.
    ImplTrait,
    /// The never type produces no comparable result.
    Never,
    /// A macro can expand the type domain after this audit.
    Macro,
    /// An inferred type does not state the model's domain.
    Infer,
    /// A named type is outside the closed primitive and `Option` set.
    Named,
    /// An array length is not a concrete integer literal.
    ArrayLength,
    /// The tuple is wider than the implementations emitted by this version.
    TupleWidth,
    /// A float result is not reflexive under `Eq` because of NaN.
    NonReflexiveFloat,
    /// `usize` and `isize` change their domain with the compilation target.
    TargetSized,
    /// Syntax added after this closed set was written.
    Unsupported,
}

/// An effect or open semantic edge outside the pure expression fragment.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Effect {
    /// Arithmetic, shifts, and negation depend on the profile's overflow semantics; Kani 0.68 exports a release build and cannot witness the measured test profile through its result protocol.
    ProfileDependentArithmetic,
    /// A free call, including recursion.
    Call,
    /// A method call whose implementation is open.
    MethodCall,
    /// A macro expansion not present in the audited tree.
    Macro,
    /// A path not bound by an argument or local.
    GlobalPath,
    /// A closure can capture state and creates a new callable body.
    Closure,
    /// Async or await introduces a state machine and executor interaction.
    Async,
    /// An unsafe block changes the memory model.
    Unsafe,
    /// A reference creates aliasing that this fragment does not model.
    Reference,
    /// A raw address exposes provenance.
    RawAddress,
    /// A `for` loop invokes the open `IntoIterator` trait.
    ForLoop,
    /// A range constructs an open library type.
    Range,
    /// A struct literal names a type outside the closed domain.
    Struct,
    /// `?` or a try block invokes open conversion machinery.
    Try,
    /// A match requires variant patterns outside this first closed fragment.
    Match,
    /// A pattern is not a plain local binding or wildcard.
    Pattern,
    /// A nested item has separate name resolution and callable state.
    NestedItem,
    /// A string-like literal allocates or borrows storage outside the scalar domain.
    Literal,
    /// A dereference observes memory through an alias.
    Dereference,
    /// A named field requires a named aggregate outside the type domain.
    NamedField,
    /// Syntax added after this closed set was written.
    Unsupported,
}

/// The stable, exhaustive classes of eligibility refusal.
#[derive(Debug, Clone, Copy, PartialEq, Eq, njutest_macros::AllVariants)]
pub(crate) enum IneligibilityKind {
    /// Source bytes are not Rust UTF-8 text.
    SourceEncoding,
    /// The candidate was minted from different source bytes.
    SourceDigest,
    /// The candidate's own identity fields disagree.
    Candidate,
    /// The cataloged ID is not the candidate's derived ID.
    Identity,
    /// The pristine source does not parse.
    SourceSyntax,
    /// The edit is not inside one top-level free function body.
    EnclosingFunction,
    /// Function modifiers are outside the fragment.
    FunctionShape,
    /// The function has no symbolic input.
    NoSymbolicInput,
    /// An argument pattern is not a plain by-value binding.
    ArgumentPattern,
    /// An input type is outside the symbolic domain.
    InputType,
    /// The output type is outside the equality domain.
    OutputType,
    /// The pristine or mutant body is not in the pure fragment.
    Effect,
    /// The edited function does not parse.
    MutantSyntax,
    /// A generated private name already occurs in the source.
    NameCollision,
    /// A source span could not be mapped back to bytes.
    SourceSpan,
}

/// Why one mutation cannot enter the model checker.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum Ineligible {
    /// The source is not UTF-8.
    SourceEncoding,
    /// The source digest no longer matches the candidate.
    SourceDigest,
    /// The candidate is internally incoherent.
    Candidate,
    /// The cataloged identity differs from the independently derived one.
    Identity,
    /// The source is not a parseable Rust file.
    SourceSyntax,
    /// The edit is not wholly inside exactly one top-level free function body.
    EnclosingFunction,
    /// The signature carries a forbidden modifier.
    FunctionShape(FunctionFeature),
    /// There is no input for a symbolic differential question.
    NoSymbolicInput,
    /// An argument is not a plain by-value local binding.
    ArgumentPattern { index: usize },
    /// One input is outside the closed domain.
    InputType { index: usize, feature: TypeFeature },
    /// The result is outside the closed equality domain.
    OutputType(TypeFeature),
    /// One rendering contains an effect or open semantic edge.
    Effect {
        rendering: Rendering,
        effect: Effect,
    },
    /// The candidate edit does not produce a parseable function.
    MutantSyntax,
    /// A deterministic generated name already exists in the subject.
    NameCollision,
    /// Parser locations did not map to the source bytes.
    SourceSpan,
}

impl Ineligible {
    /// The stable class later reports and audit schemas switch over.
    pub(crate) const fn kind(&self) -> IneligibilityKind {
        match self {
            Self::SourceEncoding => IneligibilityKind::SourceEncoding,
            Self::SourceDigest => IneligibilityKind::SourceDigest,
            Self::Candidate => IneligibilityKind::Candidate,
            Self::Identity => IneligibilityKind::Identity,
            Self::SourceSyntax => IneligibilityKind::SourceSyntax,
            Self::EnclosingFunction => IneligibilityKind::EnclosingFunction,
            Self::FunctionShape(_) => IneligibilityKind::FunctionShape,
            Self::NoSymbolicInput => IneligibilityKind::NoSymbolicInput,
            Self::ArgumentPattern { .. } => IneligibilityKind::ArgumentPattern,
            Self::InputType { .. } => IneligibilityKind::InputType,
            Self::OutputType(_) => IneligibilityKind::OutputType,
            Self::Effect { .. } => IneligibilityKind::Effect,
            Self::MutantSyntax => IneligibilityKind::MutantSyntax,
            Self::NameCollision => IneligibilityKind::NameCollision,
            Self::SourceSpan => IneligibilityKind::SourceSpan,
        }
    }
}

