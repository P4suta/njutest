//! The catalog identity Cargo embeds in an instrumented binary, and rebuilds when it changes.

#![expect(
    clippy::expect_used,
    reason = "a test reports a setup failure by panicking"
)]

use std::ffi::OsString;
use std::path::{Path, PathBuf};

use rust_mutants::cargo::{
    CompileKind, CompileOptions, Driver, LocateOptions, Message, Toolchain, compile,
};
use rust_mutants::instrument::COMPILED_CATALOG_ENV;
use rust_mutants::runner::Cancel;
use rust_mutants::session::PrepareOptions;
use rust_mutants::trace::Recorder;
use rust_mutants::workspace::{OpenOptions, Workspace};

const CAPTURE: &str = "FIXTURE_CAPTURE_COMPILED_CATALOG";

struct Project {
    root: PathBuf,
    temporary: PathBuf,
    _directory: tempfile::TempDir,
}

fn project() -> Project {
    let directory = tempfile::tempdir().expect("a temporary project");
    let root = directory.path().join("project");
    let temporary = directory.path().join("temporary");
    std::fs::create_dir_all(root.join("src")).expect("a source directory");
    std::fs::create_dir_all(&temporary).expect("a temporary directory");
    std::fs::write(
        root.join("Cargo.toml"),
        "[package]\nname = \"compiled-catalog-fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[workspace]\n",
    )
    .expect("a manifest");
    std::fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"compiled-catalog-fixture\"\nversion = \"0.1.0\"\n",
    )
    .expect("a lock file");
    std::fs::write(
        root.join("src/lib.rs"),
        r#"pub fn less(left: i32, right: i32) -> bool {
    left < right
}

#[cfg(test)]
mod tests {
    #[test]
    fn capture() {
        if let Some(path) = std::env::var_os("FIXTURE_CAPTURE_COMPILED_CATALOG") {
            std::fs::write(
                path,
                option_env!("RUST_MUTANTS_COMPILED_CATALOG").unwrap_or("missing"),
            )
            .unwrap();
        }
    }
}
"#,
    )
    .expect("a source file");
    Project {
        root,
        temporary,
        _directory: directory,
    }
}

fn capture(executable: &Path, output: &Path) -> String {
    let answer = std::process::Command::new(executable)
        .env_clear()
        .env(CAPTURE, output)
        .args(["tests::capture", "--exact"])
        .output()
        .expect("the test binary runs");
    assert!(
        answer.status.success(),
        "{}{}",
        std::str::from_utf8(&answer.stdout).expect("the fixture writes exact UTF-8"),
        std::str::from_utf8(&answer.stderr).expect("the fixture writes exact UTF-8")
    );
    std::fs::read_to_string(output).expect("the embedded catalog")
}

fn test_binary(messages: &[Message]) -> (&Path, bool) {
    messages
        .iter()
        .find_map(|message| match message {
            Message::CompilerArtifact(artifact)
                if artifact.profile.test && artifact.target.name == "compiled_catalog_fixture" =>
            {
                artifact
                    .executable
                    .as_deref()
                    .map(|executable| (executable, artifact.fresh))
            }
            _ => None,
        })
        .expect("the library test binary")
}

#[test]
fn a_session_embeds_its_complete_catalog_in_the_binary_it_builds() {
    let project = project();
    let workspace = Workspace::open(
        &project.root,
        OpenOptions {
            cargo: Some(njutest_devkit::paths::cargo_binary()),
            temp_directory: project.temporary.clone(),
            env: njutest_devkit::paths::environment_for_a_run()
                .into_iter()
                .collect(),
            offline: true,
            locked: true,
            ..OpenOptions::default()
        },
        &Cancel::new(),
    )
    .expect("open");
    let session = workspace
        .prepare(
            &PrepareOptions {
                coverage: false,
                branch_proofs: false,
                touch: false,
                doctests: false,
                ..PrepareOptions::default()
            },
            &Cancel::new(),
        )
        .expect("prepare");
    let target = session
        .targets()
        .iter()
        .find(|target| target.id == "compiled-catalog-fixture/lib/compiled_catalog_fixture")
        .expect("the library test target");
    let embedded = capture(
        &target.executable,
        &project.temporary.join("session-catalog"),
    );

    assert_eq!(embedded, session.catalog().digest());
    session.close().expect("close");
}

#[test]
fn cargo_rebuilds_an_unchanged_binary_when_the_embedded_catalog_changes() {
    let project = project();
    let target = project.temporary.join("target");
    let cancel = Cancel::new();
    let trace = Recorder::disabled();
    let toolchain = Toolchain::locate(
        &LocateOptions {
            cargo: Some(njutest_devkit::paths::cargo_binary()),
            env: Some(
                njutest_devkit::paths::environment_for_a_run()
                    .into_iter()
                    .collect(),
            ),
            ..LocateOptions::default()
        },
        &project.root,
        &cancel,
    )
    .expect("a toolchain");
    let driver = Driver {
        toolchain: &toolchain,
        dir: &project.root,
        cancel: &cancel,
        trace: &trace,
    };
    let build = |catalog: &str| {
        compile(
            &driver,
            &CompileOptions {
                kind: CompileKind::Tests,
                target_dir: Some(rust_mutants::cargo::BuildDir::new(
                    target.clone(),
                    Vec::new(),
                )),
                locked: true,
                offline: true,
                env: rust_mutants::vars::Variables::of([(
                    OsString::from(COMPILED_CATALOG_ENV),
                    OsString::from(catalog),
                )]),
                ..CompileOptions::default()
            },
        )
        .expect("compile")
    };

    let first = build("catalog-one");
    let (first_binary, first_fresh) = test_binary(&first.messages);
    assert!(!first_fresh, "the first build compiled the test binary");
    assert_eq!(
        capture(first_binary, &project.temporary.join("first-catalog")),
        "catalog-one"
    );

    let second = build("catalog-two");
    let (second_binary, second_fresh) = test_binary(&second.messages);
    assert!(
        !second_fresh,
        "option_env makes the catalog an input to Cargo's freshness decision"
    );
    assert_eq!(
        capture(second_binary, &project.temporary.join("second-catalog")),
        "catalog-two"
    );
}
