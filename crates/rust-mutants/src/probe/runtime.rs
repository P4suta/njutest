//! The module a probed file calls into: the traits that decide what can be probed, and the append that records what was.
//!
//! The traits are the whole of the type reasoning. A probe reads `==` as the
//! answer to "could this test have seen the replacement", so it is stated only
//! where equality is the whole of what a program can tell apart. `Observable`
//! names those types — the integers, `bool`, `char`, and the unit — and
//! nothing else, so a type whose `PartialEq` answers about one field while a
//! test reads another is a compile error here rather than a discharge that
//! removes the test which finds the defect. `FloatRefuse` keeps `f32` and
//! `f64` out with a type no `if` accepts: `-0.0 == 0.0` holds and `-0.0` is
//! not what `Default::default()` writes, so a probe there would say a mutation
//! changed nothing when it changed the sign of a zero.
//!
//! Every refusal is the compiler's, and every refusal leaves the site
//! unprobed, which costs an execution and never a kill.
//!
//! The log is appended to with one `write_all` per record and never read back.
//! A process that cannot open or write it exits rather than running tests whose
//! infections would go unrecorded: a missing record reads as "this test did not
//! infect that mutant", which is exactly the licence to skip work.

use std::fmt::Write as _;

/// The environment variable naming the log a probe process appends to.
pub const PROBE_ENV: &str = "RUST_MUTANTS_PROBE";

/// The exit code a probe process ends with when it cannot record what it saw.
pub const UNAVAILABLE_EXIT: i32 = 98;

/// The stem of the generated module.
pub const MODULE_STEM: &str = "__rmp";

/// The line a reader will find at the top of the generated module.
pub const MARKER: &str = "rust-mutants-probe-runtime-v1";

/// The invariant text of the probe runtime, with the per-file parts as placeholders.
const TEMPLATE: &str = r#"#[doc(hidden)]
{{ALLOW}}mod {{MODULE}} {
    // {{MARKER}} - generated by rust-mutants; DO NOT EDIT.
    const CATALOG: &str = "{{CATALOG}}";
    const COUNT: u32 = {{COUNT}};
    const INDICES: &[u32] = &[
{{INDICES}}    ];
    static SEEN: [::std::sync::atomic::AtomicBool; {{SLOTS}}] = [const { ::std::sync::atomic::AtomicBool::new(false) }; {{SLOTS}}];
    static HEADER: ::std::sync::atomic::AtomicBool = ::std::sync::atomic::AtomicBool::new(false);

    pub(crate) struct Refused;

    pub(crate) trait FloatRefuse {
        fn probed(&self) -> Refused {
            Refused
        }
    }
    impl FloatRefuse for f32 {}
    impl FloatRefuse for f64 {}

    pub(crate) trait Observable {}
    impl Observable for bool {}
    impl Observable for char {}
    impl Observable for () {}
    impl Observable for i8 {}
    impl Observable for i16 {}
    impl Observable for i32 {}
    impl Observable for i64 {}
    impl Observable for i128 {}
    impl Observable for isize {}
    impl Observable for u8 {}
    impl Observable for u16 {}
    impl Observable for u32 {}
    impl Observable for u64 {}
    impl Observable for u128 {}
    impl Observable for usize {}

    pub(crate) trait Probe {
        fn probed(&self) -> bool;
    }
    impl<T: Observable + ::std::default::Default + ::std::cmp::PartialEq> Probe for &T {
        fn probed(&self) -> bool {
            **self == <T as ::std::default::Default>::default()
        }
    }

    #[inline(always)]
    pub(crate) fn infect(slot: usize, index: u32) {
        if slot >= SEEN.len() {
            return;
        }
        if SEEN[slot].swap(true, ::std::sync::atomic::Ordering::Relaxed) {
            return;
        }
        record(index);
    }

    #[cold]
    fn record(index: u32) {
        let path = match ::std::env::var("{{PROBE_ENV}}") {
            ::std::result::Result::Ok(value) if !value.is_empty() => value,
            _ => return,
        };
        let opened = ::std::fs::OpenOptions::new().create(true).append(true).open(&path);
        let mut file = match opened {
            ::std::result::Result::Ok(file) => file,
            ::std::result::Result::Err(_) => ::std::process::exit({{EXIT}}),
        };
        if !HEADER.swap(true, ::std::sync::atomic::Ordering::Relaxed) {
            let header = ::std::format!("{{SCHEMA}} {} {}\n", CATALOG, COUNT);
            if ::std::io::Write::write_all(&mut file, header.as_bytes()).is_err() {
                ::std::process::exit({{EXIT}});
            }
        }
        let line = ::std::format!("{}\n", index);
        if ::std::io::Write::write_all(&mut file, line.as_bytes()).is_err() {
            ::std::process::exit({{EXIT}});
        }
    }

    #[inline(always)]
    pub(crate) fn slots() -> usize {
        INDICES.len()
    }
}
"#;

/// Renders the probe runtime for one file.
///
/// Every path is absolute (`::std::…`) so that a crate which renamed or
/// shadowed a prelude name still compiles, and nothing in it is `unsafe`, so a
/// crate that forbids unsafe code still does.
#[must_use]
pub fn render(module: &str, catalog_digest: &str, count: u32, indices: &[u32]) -> String {
    let mut table = String::new();
    for index in indices {
        let written = writeln!(table, "        {index},");
        debug_assert!(written.is_ok(), "writing to a String cannot fail");
    }
    TEMPLATE
        .replace("{{MODULE}}", module)
        .replace("{{ALLOW}}", crate::instrument::ALLOW_ATTRIBUTE)
        .replace("{{MARKER}}", MARKER)
        .replace("{{CATALOG}}", catalog_digest)
        .replace("{{COUNT}}", &count.to_string())
        .replace("{{INDICES}}", &table)
        .replace("{{SLOTS}}", &indices.len().max(1).to_string())
        .replace("{{PROBE_ENV}}", PROBE_ENV)
        .replace("{{SCHEMA}}", crate::probe::log::SCHEMA)
        .replace("{{EXIT}}", &UNAVAILABLE_EXIT.to_string())
}
