/// The target every guest is compiled for.
const GUEST_TARGET: &str = "wasm32-wasip1";

/// The guest program's source, compiled by the test that runs it.
const PROGRAM: &str = include_str!("../guests/program.rs");

/// The libtest guest's source, the library of a crate built with `cargo test --no-run`.
const LIBTEST: &str = include_str!("../guests/libtest.rs");

/// The libtest guest's manifest: no dependencies, and a workspace of its own so cargo never looks upwards.
const LIBTEST_MANIFEST: &str = "[package]\nname = \"sealed-libtest-guest\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n[lib]\npath = \"lib.rs\"\n\n[workspace]\n";

/// The libtest guest's lock file, which a crate with no dependencies holds only itself in.
const LIBTEST_LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"sealed-libtest-guest\"\nversion = \"0.0.0\"\n";


/// A command for `program` of the pinned toolchain, given only what a nested build needs and a temporary directory of its own.
fn pinned(program: &str, scratch: &std::path::Path) -> std::process::Command {
    let mut command = std::process::Command::new(program);
    command
        .env_clear()
        .envs(njutest_devkit::paths::environment_for_a_toolchain_run(&[]))
        .envs(njutest_devkit::paths::temporary_directory(scratch))
        .current_dir(scratch);
    command
}

/// What `command` printed, failing the test with everything it said where it did not succeed.
fn succeeded(mut command: std::process::Command, what: &str) -> std::process::Output {
    let build = command.get_program() == "cargo" && command.get_args().next() == Some(std::ffi::OsStr::new("test"));
    let started = Instant::now();
    let output = command
        .output()
        .unwrap_or_else(|error| panic!("{what} could not be started: {error}"));
    if build {
        let millis = u64::try_from(started.elapsed().as_millis()).expect("a measured build duration");
        njutest_devkit::cost::record(std::path::Path::new("sealed-guests"),
            &serde_json::json!({"builds": 1, "build_ms": millis, "units": 0, "platform": [], "platform_requests": 0, "error": null}),
            &serde_json::Value::Null).expect("the direct fixture build's cost record");
    }
    assert!(
        output.status.success(),
        "{what} failed with {}:\n{}\n{}",
        output.status,
        njutest_devkit::process::strict_utf8(&output.stdout),
        njutest_devkit::process::strict_utf8(&output.stderr)
    );
    output
}

/// The pinned `rustc`'s version banner, once the target every guest needs is known to be installed for it.
///
/// # Panics
/// The pinned toolchain is not the one on the path, or it has no `wasm32-wasip1` standard library, which is a missing precondition this says how to supply.
fn toolchain_banner(scratch: &std::path::Path) -> String {
    let channel = njutest_devkit::paths::pinned_toolchain().expect("rust-toolchain.toml pins a channel");
    let banner = succeeded(
        {
            let mut command = pinned("rustc", scratch);
            command.arg("-vV");
            command
        },
        "rustc -vV",
    );
    let banner = String::from_utf8(banner.stdout).expect("rustc -vV prints UTF-8");
    assert!(
        banner
            .lines()
            .any(|line| line.trim() == format!("release: {channel}")),
        "the guests are compiled by the toolchain rust-toolchain.toml pins, {channel}, and the \
         `rustc` this test reaches is another:\n{banner}"
    );
    let libdir = succeeded(
        {
            let mut command = pinned("rustc", scratch);
            command.args(["--print", "target-libdir", "--target", GUEST_TARGET]);
            command
        },
        "rustc --print target-libdir",
    );
    let libdir = String::from_utf8(libdir.stdout).expect("rustc prints a UTF-8 path");
    match std::fs::metadata(libdir.trim()) {
        Ok(_installed) => banner,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => panic!(
            "the {GUEST_TARGET} target is not installed for the pinned toolchain {channel}, and \
             every sealed guest is compiled for it: run `rustup target add {GUEST_TARGET} \
             --toolchain {channel}`"
        ),
        Err(error) => panic!("{}: {error}", libdir.trim()),
    }
}

/// Where compiled guests are kept between test processes, each under the digest of everything that went into it.
fn guest_cache() -> std::path::PathBuf {
    let cache = std::path::Path::new(env!("CARGO_TARGET_TMPDIR")).join("sealed-guests");
    std::fs::create_dir_all(&cache).expect("the guest cache can be made");
    cache
}

/// The bytes kept under `key`, or the ones `build` makes in a scratch directory and keeps there.
fn cached(key: &str, build: impl FnOnce(&std::path::Path) -> Vec<u8>) -> Vec<u8> {
    let cache = guest_cache();
    let kept = cache.join(format!("{key}.wasm"));
    match std::fs::read(&kept) {
        Ok(bytes) => return bytes,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => panic!("{}: {error}", kept.display()),
    }
    let scratch = tempfile::tempdir_in(&cache).expect("a scratch directory in the guest cache");
    let bytes = build(scratch.path());
    let staged = scratch.path().join("staged.wasm");
    std::fs::write(&staged, &bytes).expect("the compiled guest can be staged");
    if let Err(error) = std::fs::rename(&staged, &kept)
        && std::fs::metadata(&kept).is_err()
    {
        panic!("{}: {error}", kept.display());
    }
    bytes
}

/// The digest naming a guest in the cache: its sources, the toolchain, and how it is built.
fn cache_key(name: &str, parts: &[&str]) -> String {
    let mut all = Vec::new();
    for part in parts {
        all.extend_from_slice(part.len().to_string().as_bytes());
        all.push(b':');
        all.extend_from_slice(part.as_bytes());
    }
    format!("{name}-{}", rust_mutants_sealed::SealedDigest::of(&all))
}

/// The flags every single-file guest is compiled with: optimized enough that recursion lives on the native stack.
const PROGRAM_FLAGS: [&str; 6] = ["--edition", "2024", "-C", "opt-level=1", "--target", GUEST_TARGET];

/// What every single-file guest is linked with so the host can start it in a directory, spelled as `rustc` takes a linker argument.
fn start_flags() -> Vec<String> {
    rust_mutants_sealed::START_LINK_ARGS
        .iter()
        .map(|argument| format!("-Clink-arg={argument}"))
        .collect()
}

/// The guest program, compiled for `wasm32-wasip1` by the pinned `rustc`.
fn program_bytes() -> Vec<u8> {
    let probe = tempfile::tempdir().expect("a scratch directory");
    let banner = toolchain_banner(probe.path());
    let key = cache_key(
        "program",
        &[
            PROGRAM,
            &banner,
            &PROGRAM_FLAGS.join(" "),
            &start_flags().join(" "),
        ],
    );
    cached(&key, |scratch| {
        let source = scratch.join("program.rs");
        std::fs::write(&source, PROGRAM).expect("the guest source can be written");
        let output = scratch.join("program.wasm");
        let mut command = pinned("rustc", scratch);
        command
            .args(PROGRAM_FLAGS)
            .args(start_flags())
            .arg("-o")
            .arg(&output)
            .arg(&source);
        succeeded(command, "rustc for the guest program");
        std::fs::read(&output).expect("rustc wrote the guest")
    })
}

/// The libtest guest's test harness, built by the pinned `cargo test --no-run` for `wasm32-wasip1`.
fn libtest_bytes() -> Vec<u8> {
    let probe = tempfile::tempdir().expect("a scratch directory");
    let banner = toolchain_banner(probe.path());
    let key = cache_key("libtest", &[LIBTEST, LIBTEST_MANIFEST, LIBTEST_LOCK, &banner]);
    cached(&key, |scratch| {
        let project = scratch.join("project");
        std::fs::create_dir_all(&project).expect("the guest project directory can be made");
        std::fs::write(project.join("Cargo.toml"), LIBTEST_MANIFEST).expect("manifest");
        std::fs::write(project.join("Cargo.lock"), LIBTEST_LOCK).expect("lock file");
        std::fs::write(project.join("lib.rs"), LIBTEST).expect("library source");
        let mut command = pinned("cargo", &project);
        command.args([
            "test",
            "--no-run",
            "--offline",
            "--locked",
            "--message-format=json",
            "--target",
            GUEST_TARGET,
        ]);
        let built = succeeded(command, "cargo test --no-run for the libtest guest");
        let stdout = String::from_utf8(built.stdout).expect("cargo prints UTF-8");
        let harness = stdout
            .lines()
            .find_map(|line| {
                let message: serde_json::Value =
                    njutest_devkit::strictjson::decode_str(line).expect("cargo prints JSON");
                let executable = message.get("executable")?.as_str()?.to_owned();
                (message.get("reason")?.as_str()? == "compiler-artifact").then_some(executable)
            })
            .expect("cargo names the test harness it built");
        std::fs::read(&harness).expect("the harness cargo named is readable")
    })
}
