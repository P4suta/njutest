impl<'de> Deserialize<'de> for CheckId {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let value = serde_json::Value::deserialize(deserializer)?;
        match value {
            serde_json::Value::Number(number) => number
                .as_u64()
                .map(Self::Number)
                .ok_or_else(|| serde::de::Error::custom("check id must be an unsigned integer")),
            serde_json::Value::String(text) => Ok(Self::Text(text)),
            serde_json::Value::Null
            | serde_json::Value::Bool(_)
            | serde_json::Value::Array(_)
            | serde_json::Value::Object(_) => Err(serde::de::Error::custom(
                "check id must be an unsigned integer or string",
            )),
        }
    }
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Location {
    file: String,
    line: String,
    column: String,
}

fn validate_document(
    document: &Document,
    evidence: &Evidence,
    answer: Answer,
) -> Result<(), Failure> {
    validate_context(document, evidence)?;
    validate_harness(document, evidence, answer)?;
    let [details] = document.property_details.as_slice() else {
        return Err(Failure::Decision(
            "there is not exactly one property count record",
        ));
    };
    let [result] = document.verification_results.results.as_slice() else {
        return Err(Failure::Decision(
            "there is not exactly one verification result",
        ));
    };
    validate_result(ResultInput {
        summary: &document.verification_results.summary,
        details,
        result,
        identity: &evidence.identity,
        answer,
    })
}

fn validate_context(document: &Document, evidence: &Evidence) -> Result<(), Failure> {
    let verifier = &evidence.verifier;
    let backend = &verifier.backend;
    if document.metadata.version != backend.export_version
        || document.metadata.kani_version != verifier.tool
        || document.metadata.target != backend.target
        || document.metadata.build_mode != backend.build_mode
        || document.tools.kani != verifier.tool
        || document.tools.rustc != backend.rustc
        || document.tools.cbmc != backend.cbmc
        || document.tools.goto_cc != backend.goto_cc
        || document.tools.goto_instrument != backend.goto_instrument
        || !matches!(document.tools.solvers.as_slice(), [Solver { name, version: Nullable(None) }] if name == &backend.solver)
        || document.metadata.timestamp.trim().is_empty()
        || !matches!(document.project.crate_name.as_slice(), [name] if name == MODEL_CRATE_NAME)
        || !clean_absolute(Path::new(&document.project.workspace_root))
        || !clean_absolute(Path::new(&document.project.output_dir))
        || document.coverage.enabled
    {
        return Err(Failure::Decision(
            "metadata, project, tool, or backend facts differ",
        ));
    }
    Ok(())
}

fn validate_harness(
    document: &Document,
    evidence: &Evidence,
    answer: Answer,
) -> Result<(), Failure> {
    let [metadata] = document.harness_metadata.as_slice() else {
        return Err(Failure::Decision(
            "there is not exactly one harness metadata record",
        ));
    };
    let [errors] = document.error_details.as_slice() else {
        return Err(Failure::Decision(
            "there is not exactly one harness error record",
        ));
    };
    let [details] = document.property_details.as_slice() else {
        return Err(Failure::Decision(
            "there is not exactly one property count record",
        ));
    };
    let [cbmc] = document.cbmc.as_slice() else {
        return Err(Failure::Decision("there is not exactly one CBMC record"));
    };
    let [result] = document.verification_results.results.as_slice() else {
        return Err(Failure::Decision(
            "there is not exactly one verification result",
        ));
    };
    if metadata.pretty_name != evidence.identity.harness
        || metadata.mangled_name.trim().is_empty()
        || !matches!(document.project.crate_name.as_slice(), [name] if name == &metadata.crate_name)
        || Path::new(&metadata.source.file) != Path::new(MODEL_SOURCE_PATH)
        || metadata.source.start_line == 0
        || metadata.source.end_line < metadata.source.start_line
        || !clean_absolute(Path::new(&metadata.goto_file))
        || !strict_descendant(
            Path::new(&metadata.goto_file),
            Path::new(&document.project.output_dir),
        )
        || metadata.attributes.kind != "Proof"
        || metadata.attributes.should_panic
        || metadata
            .contract
            .contracted_function_name
            .0
            .as_ref()
            .is_some()
        || metadata.contract.recursion_tracker.0.as_ref().is_some()
        || metadata.has_loop_contracts.0
        || metadata.is_automatically_generated.0
        || metadata.is_bounded.0
        || metadata.is_ctor_based.0
        || !errors.coherent_with(answer)
        || !same_harnesses(
            &evidence.identity.harness,
            [
                errors.harness_id(),
                details.harness_id.as_str(),
                cbmc.harness_id.as_str(),
                result.harness_id.as_str(),
            ],
        )
        || cbmc.metadata.version != CBMC_SHORT
        || cbmc.metadata.os_info.trim().is_empty()
        || cbmc.configuration.object_bits != 16
        || cbmc.configuration.solver != SOLVER
        || !stats(&cbmc.stats)
    {
        return Err(Failure::Decision(
            "harness or CBMC facts differ from the closed protocol",
        ));
    }
    Ok(())
}

fn clean_absolute(path: &Path) -> bool {
    path.is_absolute()
        && path.components().all(|component| {
            matches!(
                component,
                Component::Prefix(_) | Component::RootDir | Component::Normal(_)
            )
        })
}

fn strict_descendant(child: &Path, parent: &Path) -> bool {
    if !clean_absolute(child) || !clean_absolute(parent) {
        return false;
    }
    let child = protocol_path(child);
    let parent = protocol_path(parent);
    child != parent && child.starts_with(parent)
}

fn protocol_path(path: &Path) -> std::borrow::Cow<'_, Path> {
    #[cfg(target_os = "macos")]
    {
        for alias in ["var", "tmp", "etc"] {
            let private = Path::new("/private").join(alias);
            match path.strip_prefix(&private) {
                Ok(tail) => {
                    return std::borrow::Cow::Owned(Path::new("/").join(alias).join(tail));
                }
                Err(_different_prefix) => {}
            }
        }
    }
    std::borrow::Cow::Borrowed(path)
}

fn same_harnesses<const N: usize>(expected: &str, actual: [&str; N]) -> bool {
    actual.into_iter().all(|one| one == expected)
}

fn stats(stats: &CbmcStats) -> bool {
    let times = [
        stats.runtime_symex_s.0,
        stats.runtime_postprocess_equation_s.0,
        stats.runtime_convert_ssa_s.0,
        stats.runtime_post_process_s.0,
        stats.runtime_solver_s.0,
        stats.runtime_decision_procedure_s.0,
    ];
    let time_ok = times
        .into_iter()
        .all(|value| value.is_none_or(|value| value.is_finite() && value >= 0.0));
    time_ok
        && stats.vccs_remaining <= stats.vccs_generated
        && stats.size_program_expression > 0
        && stats.slicing_removed_assignments <= stats.size_program_expression
}

#[derive(Debug, Clone, Copy)]
struct ResultInput<'a> {
    summary: &'a Summary,
    details: &'a PropertyDetail,
    result: &'a HarnessResult,
    identity: &'a Identity,
    answer: Answer,
}

fn validate_result(input: ResultInput<'_>) -> Result<(), Failure> {
    let ResultInput {
        summary,
        details,
        result,
        identity,
        answer,
    } = input;
    validate_result_summary(summary, result)?;
    let observed = observed_counts(&result.checks)?;
    if details.property_details != observed {
        return Err(Failure::Decision(
            "property counters differ from property statuses",
        ));
    }
    if result.checks.iter().any(incomplete_check) {
        return Err(Failure::Decision(
            "a property identity or location is incomplete",
        ));
    }
    let tagged: Vec<_> = result
        .checks
        .iter()
        .filter(|check| check.description == identity.assertion)
        .collect();
    let [tagged] = tagged.as_slice() else {
        return Err(Failure::Decision(
            "the tagged assertion is absent or duplicated",
        ));
    };
    if tagged.category != "assertion"
        || result
            .checks
            .iter()
            .any(|check| check.category == "unwind" && check.status == Status::Failure)
        || result
            .checks
            .iter()
            .filter(|check| check.description != identity.assertion)
            .any(|check| check.status != Status::Success)
    {
        return Err(Failure::Decision(
            "a safety or unwind property did not succeed",
        ));
    }
    validate_answer(summary, result, tagged, answer)
}

fn validate_result_summary(summary: &Summary, result: &HarnessResult) -> Result<(), Failure> {
    let classified = summary
        .successful
        .checked_add(summary.failed)
        .ok_or(Failure::Decision("summary result counters overflow"))?;
    if summary.total_harnesses != 1
        || summary.executed != 1
        || summary.status != "completed"
        || classified != 1
        || summary.duration_ms == 0
        || result.duration_ms == 0
    {
        return Err(Failure::Decision("summary is not one completed harness"));
    }
    Ok(())
}

fn incomplete_check(check: &Check) -> bool {
    !check_id(&check.id)
        || check.function.trim().is_empty()
        || check.location.file.trim().is_empty()
        || check.location.line.trim().is_empty()
        || check.location.column.trim().is_empty()
}

fn validate_answer(
    summary: &Summary,
    result: &HarnessResult,
    tagged: &Check,
    answer: Answer,
) -> Result<(), Failure> {
    let coherent = match answer {
        Answer::Proved => {
            tagged.status == Status::Success
                && result.status == Status::Success
                && summary.successful == 1
                && summary.failed == 0
        }
        Answer::Noticed => {
            tagged.status == Status::Failure
                && result.status == Status::Failure
                && summary.successful == 0
                && summary.failed == 1
        }
    };
    if !coherent {
        return Err(Failure::Decision(
            "tagged property, harness, and summary disagree",
        ));
    }
    Ok(())
}

fn observed_counts(checks: &[Check]) -> Result<PropertyCounts, Failure> {
    let count = |predicate: fn(Status) -> bool| {
        u64::try_from(
            checks
                .iter()
                .filter(|check| predicate(check.status))
                .count(),
        )
        .map_err(|_error| Failure::Decision("property count does not fit u64"))
    };
    Ok(PropertyCounts {
        total_properties: u64::try_from(checks.len())
            .map_err(|_error| Failure::Decision("property count does not fit u64"))?,
        passed: count(|status| status == Status::Success)?,
        failed: count(|status| status == Status::Failure)?,
        unreachable: count(|status| status == Status::Unreachable)?,
        undetermined: count(|status| matches!(status, Status::Undetermined | Status::Unknown))?,
        solver_error: count(|status| status == Status::Error)?,
        satisfied: count(|status| status == Status::Satisfied)?,
        unsatisfiable: count(|status| status == Status::Unsatisfiable)?,
        covered: count(|status| status == Status::Covered)?,
        uncovered: count(|status| status == Status::Uncovered)?,
    })
}

fn check_id(id: &CheckId) -> bool {
    match id {
        CheckId::Number(number) => *number > 0,
        CheckId::Text(text) => !text.trim().is_empty(),
    }
}

