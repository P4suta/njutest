//! Independent verification of one affirmative `verified-v1` report record.
//!
//! This module deliberately shares no parser or decision type with
//! `njutest-cli`. It reads the retained source and Kani export again and
//! re-derives the answer from the pinned protocol.

use std::collections::BTreeSet;
use std::io::Read as _;
use std::path::{Component, Path};

use serde::{Deserialize, Serialize};
use sha2::Digest as _;

const KANI: &str = "0.68.0";
const EXPORT: &str = "1.0";
const BUILD_MODE: &str = "release";
const RUSTC: &str = "rustc 1.100.0-nightly (8925ea358 2026-08-20)";
const CBMC: &str = "6.11.0 (cbmc-6.11.0)";
const CBMC_SHORT: &str = "6.11.0";
const GOTO_CC: &str = "clang version 21.0.0 (goto-cc 6.11.0 (cbmc-6.11.0))";
const GOTO_INSTRUMENT: &str = "6.11.0 (cbmc-6.11.0)";
const SOLVER: &str = "cadical";
const LIMIT: u64 = 16 * 1024 * 1024;
const MODEL_CRATE_NAME: &str = "njutest_verified_model";
const MODEL_PACKAGE: &str = "njutest-verified-model";
const MODEL_EDITION: &str = "2024";
const MODEL_SOURCE_PATH: &str = "src/lib.rs";
const MODEL_ENVIRONMENT_POLICY: &str = "minimal-v1";
const MODEL_DEPENDENCY_POLICY: &str = "empty-lock-offline-v1";
const MODEL_MANIFEST: &str = "[package]\nname = \"njutest-verified-model\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\nautobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n\n[lib]\npath = \"src/lib.rs\"\n\n[workspace]\n";
const MODEL_LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"njutest-verified-model\"\nversion = \"0.0.0\"\n";
const MODEL_CRATE_DIGEST_DOMAIN: &str = "njutest-model-crate-v1";

/// The affirmative answer the report claims.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Answer {
    /// Every property succeeded.
    Proved,
    /// Only the tagged equality assertion failed.
    Noticed,
}

/// Report and filesystem facts needed to re-decide one model record.
#[derive(Debug, Clone, Copy)]
pub struct Input<'a> {
    /// Directory that contains the report and retained artifacts.
    pub run: &'a Path,
    /// Target triple recorded for the measured build.
    pub report_target: &'a str,
    /// Full mutation identity from the enclosing model record.
    pub mutant: &'a str,
    /// Affirmative answer claimed by the report.
    pub answer: Answer,
    /// Nested evidence object from that model record's explicit answer.
    pub evidence: &'a serde_json::Value,
}

/// Report and filesystem facts needed to validate one non-affirmative model
/// attempt. This never upgrades the attempt into an affirmative answer.
#[derive(Debug, Clone, Copy)]
pub struct AttemptInput<'a> {
    /// Directory that contains the report and retained artifacts.
    pub run: &'a Path,
    /// Target triple recorded for the measured build.
    pub report_target: &'a str,
    /// Full mutation identity from the enclosing model record.
    pub mutant: &'a str,
    /// Typed uncertainty reason asserted by the enclosing record.
    pub reason: &'a serde_json::Value,
    /// Attempt evidence carried by the undecided record.
    pub evidence: &'a serde_json::Value,
}

/// Why retained model evidence does not independently establish its claim.
#[derive(Debug, thiserror::Error)]
pub enum Failure {
    /// The report-side evidence shape is not exact.
    #[error("the report-side model evidence is not the closed verified-v1 shape: {0}")]
    Report(serde_json::Error),
    /// A retained artifact path escapes the run directory.
    #[error("the retained artifact path {0:?} is not confined to the run directory")]
    Path(String),
    /// A retained artifact is absent, not regular, too large, or unreadable.
    #[error("the retained artifact {path:?} cannot be audited: {detail}")]
    Artifact {
        /// The path recorded in the report.
        path: String,
        /// The exact refusal.
        detail: String,
    },
    /// Report identity, digest, process, or backend facts contradict each other.
    #[error("the report-side model evidence contradicts itself: {0}")]
    Evidence(&'static str),
    /// The raw Kani export is not the exact pinned schema.
    #[error("the retained Kani export is not the pinned 0.68 schema: {0}")]
    Export(serde_json::Error),
    /// The independently derived Kani decision differs from the report.
    #[error("the retained Kani export does not establish the reported answer: {0}")]
    Decision(&'static str),
}

